def _variant(tmp_path: Path, name: str, published: str, revised, bump: float = 0.0) -> Path:
    """The published-field fixture with new title dates and ZZA's G&A occupied changed."""
    wb = load_workbook(PUBLISHED_FIELD)
    ws = wb["NHS Trust by Sector"]
    ws["C8"], ws["C9"] = published, revised
    for row in ws.iter_rows(min_row=16):
        if row[4].value == "ZZA":
            row[13].value = row[13].value + bump
    p = tmp_path / "data" / "external" / "kh03" / "raw" / name
    p.parent.mkdir(parents=True, exist_ok=True)
    wb.save(p)
    return p


def _manifest(tmp_path: Path, records: list[dict]) -> Path:
    path = tmp_path / "data" / "external" / "kh03" / "raw" / "manifest.jsonl"
    for r in records:
        external.append_jsonl(r, path)
    return path


def test_build_orders_versions_drops_reuploads_and_supports_as_of(tmp_path):
    orig = _variant(tmp_path, "orig.xlsx", "18th August 2016", None)
    rev = _variant(tmp_path, "rev.xlsx", "18th August 2016", "23rd November 2017", bump=5)
    reup = _variant(tmp_path, "reup.xlsx", "18th August 2016", "23rd November 2017", bump=5)
    broken = tmp_path / "data" / "external" / "kh03" / "raw" / "broken.xlsx"
    broken.write_bytes(b"not a workbook")

    def rec(p, url, published, why="title_block_published"):
        return {"url": url, "filename": p.name, "period": "2016-04-01", "stored": True,
                "sha256": p.name, "path": str(p.relative_to(tmp_path)),
                "published": published, "published_source": why}

    manifest = _manifest(tmp_path, [
        rec(orig, UP + "2016/08/orig.xlsx", "2016-08-18"),
        rec(rev, UP + "2017/11/rev.xlsx", "2017-11-23", "title_block_revised"),
        rec(reup, UP + "2023/05/reup.xlsx", "2023-05-31", "upload_month_end"),
        rec(broken, UP + "2017/11/broken.xlsx", "2017-11-23"),
        {"url": UP + "gone.xlsx", "error": "gone", "stored": False},
    ])
    df, failures = kh03.build(manifest, tmp_path, out_path=None)
    assert len(failures) == 1 and failures.iloc[0].source_file == "broken.xlsx"
    assert sorted(df.source_file.unique()) == ["orig.xlsx", "rev.xlsx"]  # re-upload dropped
    assert set(df.fy_quarter) == {"2016-17 Q1"}
    assert (df.quarter_end == pd.Timestamp("2016-06-30")).all()
    assert (df.first_published == pd.Timestamp("2016-08-18")).all()
    v = df.drop_duplicates("source_file").set_index("source_file")
    assert v.loc["orig.xlsx", "version"] == 1 and not v.loc["orig.xlsx", "is_latest"]
    assert v.loc["rev.xlsx", "version"] == 2 and v.loc["rev.xlsx", "is_latest"]
    assert (df.n_versions == 2).all()
    zza = df[df.org_code == "ZZA"].set_index("version").ga_occupied
    assert zza[2] - zza[1] == 5
    assert df.loc[df.org_code == "ZZB", "dq_flag"].iloc[0] == "revised_return"

    def zza_on(when, **kw):
        cur = kh03.as_of(df, when, **kw)
        return cur.loc[cur.org_code == "ZZA", "ga_occupied"].tolist()

    assert zza_on("2016-08-17") == []
    assert zza_on("2016-08-18") == [zza[1]]
    assert zza_on("2017-11-22") == [zza[1]]
    assert zza_on("2017-11-23") == [zza[2]]
    assert zza_on("2016-09-01", use_first_published=True) == [zza[2]]  # the leaky shortcut

    vt = kh03.versions(df).set_index("version")
    assert list(vt.fy_quarter.unique()) == ["2016-17 Q1"]
    assert vt.loc[1, "lag_days"] == 49 and vt.loc[2, "lag_days"] == 511  # after 30 June 2016
    assert vt.loc[2, "orgs_changed"] == 1 and vt.loc[2, "orgs_added"] == 0
    assert np.isnan(vt.loc[1, "orgs_changed"])


