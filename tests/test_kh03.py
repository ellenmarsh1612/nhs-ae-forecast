class _Resp:
    def __init__(self, status: int, content: bytes = b""):
        self.status_code, self.content = status, content

    def raise_for_status(self):
        if self.status_code >= 400:
            raise requests.HTTPError(str(self.status_code), response=self)


class FakeNHS:
    def __init__(self, pages: dict[str, str], files: dict[str, bytes]):
        self.pages, self.files, self.calls = pages, files, []

    def get(self, url, **kw):
        self.calls.append(url)
        if url in self.pages:
            return _Resp(200, self.pages[url].encode())
        if url in self.files:
            return _Resp(200, self.files[url])
        return _Resp(404)


class FakeWayback:
    """Page captures, an upload index and file captures, all in memory."""

    def __init__(self, captures: dict[str, list[tuple[str, str]]], index: list[str],
                 files: dict[str, bytes]):
        self.captures, self.index, self.files = captures, index, files

    def cdx(self, params):
        url = params["url"]
        if params.get("matchType") == "prefix":
            return [["20240101000000", u] for u in self.index if url in u]
        for page, caps in self.captures.items():
            if page.split("://", 1)[-1] == url:
                return [[ts, page, f"D{ts}"] for ts, _ in caps]
        return [["20200101000000"]] if any(url in u for u in self.files) else []

    def fetch_capture(self, cap: PageCapture) -> str:
        return dict(self.captures[cap.url])[cap.timestamp]

    def fetch_file(self, url, ts):
        return self.files[url]


def _page(links: list[tuple[str, str]]) -> str:
    return "<html><body>" + "".join(f'<a href="{u}">{t}</a>' for u, t in links) + "</body></html>"


def test_collect_finds_superseded_and_gone_versions(tmp_path):
    orig_url = UP + "2016/08/Beds-Open-Overnight-Web_File-Q1-2016-17.xlsx"
    rev_url = UP + "2017/11/Beds-Open-Overnight-Web_File-Q1-2016-17-Final-98123.xlsx"
    gone_url = UP + "2016/09/Beds-Open-Overnight-Web_File-Q1-2016-17-v2.xlsx"
    label = "NHS organisations in England, Quarter 1, 2016-17"
    orig = _variant(tmp_path, "o.xlsx", "18th August 2016", None).read_bytes()
    rev = _variant(tmp_path, "r.xlsx", "18th August 2016", "23rd November 2017", 5).read_bytes()
    nhs = FakeNHS(
        pages={kh03.PAGE_URL: _page([(rev_url, label + " (revised 23.11.2017)")])},
        files={orig_url: orig, rev_url: rev})  # gone_url is no longer served
    wb = FakeWayback(
        captures={kh03.PAGE_URL: [("20160901000000", _page([(orig_url.replace(
            "https://", "http://"), label)])), ("20171201000000", _page([(rev_url, label)]))]},
        index=[gone_url], files={gone_url: orig})
    raw = tmp_path / "data" / "external" / "kh03" / "raw"
    spec = external.SourceSpec(
        name="kh03", pages=(kh03.PAGE_URL,), raw_dir=raw, manifest_path=raw / "manifest.jsonl",
        project_root=tmp_path, extract_links=kh03.extract_links,
        link_from_url=kh03.link_from_url, read_dates=kh03.read_dates, index_years=(2016,),
        index_regex=kh03.INDEX_REGEX)
    summary = external.collect(spec, fetcher=external.Fetcher(nhs, delay=0), wayback=wb)
    assert summary["urls"] == 3 and summary["failed"] == 0
    assert summary["stored"] == 2 and summary["duplicates"] == 1  # gone_url == orig bytes

    m = {r["url"]: r for r in read_manifest(raw / "manifest.jsonl")}
    assert m[orig_url]["first_seen"] == "2016-09-01" and not m[orig_url]["on_live_page"]
    assert m[orig_url]["published"] == "2016-08-18"
    assert m[orig_url]["published_source"] == "title_block_published"
    assert m[rev_url]["on_live_page"] and m[rev_url]["published"] == "2017-11-23"
    assert m[rev_url]["link_revised"] == "2017-11-23"
    assert m[gone_url]["fetched_from"].startswith("wayback:")
    assert m[gone_url]["stored"] is False and "identical_to" in m[gone_url]

    # A second run fetches only the live page's files again (in-place replacement check).
    nhs.calls.clear()
    summary = external.collect(spec, fetcher=external.Fetcher(nhs, delay=0), wayback=wb)
    assert summary["skipped"] == 2 and summary["fetched"] == 1
    assert rev_url in nhs.calls and orig_url not in nhs.calls

    df, failures = kh03.build(raw / "manifest.jsonl", tmp_path, out_path=None)
    assert failures.empty and sorted(df.version.unique()) == [1, 2]
    assert external.manifest_versions(read_manifest(raw / "manifest.jsonl"))[0]["urls"]


