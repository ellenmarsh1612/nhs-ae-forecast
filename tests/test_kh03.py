def test_resolve_published_reuploads_are_dated_by_upper_bounds():
    # Revised 19 June 2024, but the bytes sit in the 2024/07 folder: not public in June
    d, why = resolve_published(date(2024, 5, 23), date(2024, 6, 19), None,
                               date(2024, 7, 1), date(2024, 7, 25))
    assert d == date(2024, 7, 25) and why.startswith("first_page_capture")
    assert "precedes upload folder 2024-07" in why
    # ... and with no Archive sighting, the end of the upload month
    d, why = resolve_published(date(2020, 5, 21), date(2020, 11, 19), None,
                               date(2023, 5, 1), None)
    assert d == date(2023, 5, 31) and why.startswith("upload_month_end")
    # a sighting before the upload month is ignored (it cannot be these bytes)
    d, _ = resolve_published(None, None, None, date(2023, 5, 1), date(2021, 1, 1))
    assert d == date(2023, 5, 31)
    assert resolve_published(None, None, None, None, None) == (None, "unknown")


